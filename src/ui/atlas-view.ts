  deep_teal: { base: ["#0D1E1E", "#091616", "#050D0D"], g: ["rgba(40,170,155,0.22)", "rgba(30,120,150,0.20)", "rgba(70,190,170,0.22)", "rgba(18,50,50,0.55)"], light: "rgba(150,245,225,0.5)", tile: "50,140,130", dark: "10,22,22" },
  violet_night: { base: ["#1A1230", "#120C22", "#0A0714"], g: ["rgba(150,90,230,0.24)", "rgba(210,90,180,0.18)", "rgba(110,80,230,0.22)", "rgba(45,30,75,0.55)"], light: "rgba(225,185,255,0.55)", tile: "130,90,200", dark: "20,14,32" },
  warm: { base: ["#1C1712", "#15110D", "#0E0B09"], g: ["rgba(255,170,90,0.22)", "rgba(255,190,120,0.20)", "rgba(255,160,80,0.30)", "rgba(90,70,55,0.55)"], light: "rgba(255,205,140,0.7)", tile: "170,120,80", dark: "20,18,16" },
