const DEVICE_KEY = "atlas-home.device";
interface DevicePrefs { variant?: Variant; accent?: string }
const loadPrefs = (): DevicePrefs => {
  try {
    return JSON.parse(localStorage.getItem(DEVICE_KEY) ?? "{}");
  } catch {
    return {};
  }
};
const savePrefs = (p: DevicePrefs) => {
  try {
    localStorage.setItem(DEVICE_KEY, JSON.stringify(p));
  } catch {
    /* storage blocked: preference stays for this page only */
  }
};

const rgb = (hex: string) => [1, 3, 5].map((i) => parseInt(hex.slice(i, i + 2), 16)).join(",");

// Shared across view instances so camera reveal etc. survive view switches in one session.
const UI_STATE: Record<string, unknown> = {};

export class AtlasView extends LitElement {
  static styles = styles;
  static properties = {
    hass: { attribute: false },
    _config: { state: true },
    _confirm: { state: true },
    _settings: { state: true },
    _prefs: { state: true },
    _narrow: { state: true },
    _tick: { state: true },
  };

  declare hass?: HomeAssistant;
  declare _config?: AtlasViewCardConfig;
  declare _confirm?: { title: string; text: string; ok: string; action: () => unknown };
  declare _settings: boolean;
  declare _prefs: DevicePrefs;
  declare _narrow: boolean;
  declare _tick: number;
  private _timer?: number;
  private _mq?: MediaQueryList;
  private _relevant?: Set<string>;

  constructor() {
    super();
    this._settings = false;
    this._prefs = loadPrefs();
    this._narrow = false;
    this._tick = 0;
  }

  setConfig(config: AtlasViewCardConfig) {
    if (!config?.atlas) throw new Error("atlas-view is generated by the ATLAS Home dashboard strategy");
    this._config = config;
    const c = config.atlas;
    this._relevant = new Set([
      ...mappedEntities(c),
      ...(c.alerts?.temperature_rules ?? []).map((r) => r.entity),
      ...(c.alerts?.exterior_doors ?? []),
      ...(c.alerts?.interior_doors ?? []),
      ...(c.alerts?.critical ?? []),
      ...[c.alerts?.mailbox, c.alerts?.mailbox_ack].filter((x): x is string => !!x),
      ...(c.entities?.exclude_lights ?? []),
      ...meterEntities(c),
      // Remote card entities: re-render only, not part of the data-quality alert
      // (many TVs report unavailable while switched off).
      ...rooms(c).flatMap((r) => [r.remote_media_player, r.remote_entity]).filter((x): x is string => !!x),
    ]);
    if (config.view === "room") this._prepareCamera(cameraOf(roomById(c, config.room)));
    const fc = this._floorCameras();
    if (fc.mode === "live") this._prepareCamera(fc.cameras[0]);
  }

  /** Camera wall of the floor shown in a Rooms view (empty when off or not a Rooms view). */
  private _floorCameras(): { mode: string; cameras: string[] } {
    const c = this._config;
    if (!c || c.view !== "rooms") return { mode: "off", cameras: [] };
    const f = floorById(c.atlas, c.floor) ?? floors(c.atlas)[0];
    const mode = f?.cameras ?? "off";
    if (mode === "off") return { mode, cameras: [] };
    const cams = roomsOnFloor(c.atlas, f!.id).map((r) => cameraOf(r)).filter((x): x is string => !!x);
    return { mode, cameras: cams };
  }

  getCardSize() {
    return 12;
  }

  connectedCallback() {
    super.connectedCallback();
    // Home refreshes camera stills every 10 s (same interval as HA's picture cards); other views only need the clock.
    // Floor camera walls with snapshots refresh at the same 10 s.
    const every = this._config?.view === "home" || this._floorCameras().mode !== "off" ? 10_000 : 30_000;
    this._timer = window.setInterval(() => (this._tick = Date.now()), every);
    this._mq = window.matchMedia("(max-width: 760px)");
    this._narrow = this._mq.matches;
    this._mq.addEventListener("change", this._onMq);
  }

  disconnectedCallback() {
    super.disconnectedCallback();
    window.clearInterval(this._timer);
    this._mq?.removeEventListener("change", this._onMq);
  }

  private _onMq = (e: MediaQueryListEvent) => (this._narrow = e.matches);

  // Re-render only when an entity the dashboard uses changed (hass updates on every state change).
  protected shouldUpdate(changed: PropertyValues) {
    if (changed.size > 1 || !changed.has("hass")) return true;
    const old = changed.get("hass") as HomeAssistant | undefined;
    if (!old || !this.hass || !this._relevant) return true;
    // Embedded own cards track their own entities: always hand them the new hass.
    this.renderRoot?.querySelectorAll?.("atlas-hui-card").forEach((el) => ((el as AtlasHuiCard).hass = this.hass));
    for (const id of this._relevant) if (old.states[id] !== this.hass.states[id]) return true;
    return false;
  }

  // HA lazy-loads ha-camera-stream. Creating a picture-glance card imports it.
  private async _prepareCamera(camera?: string) {
    if (!camera || customElements.get("ha-camera-stream")) return;
    try {
      const helpers = await (window as any).loadCardHelpers?.();
      helpers?.createCardElement({ type: "picture-glance", entities: [], camera_image: camera });
      await customElements.whenDefined("ha-camera-stream");
      this.requestUpdate();
    } catch {
      /* Live falls back to the more-info dialog */
    }
  }

  private _call = async (domain: string, service: string, data: Record<string, unknown>) => {
    try {
      await this.hass!.callService(domain, service, data);
    } catch (e: any) {
      fireEvent(this, "hass-notification", { message: `ATLAS: ${domain}.${service} failed: ${e?.message ?? e}` });
    }
  };

  private _ctx(alerts: AtlasAlert[]): Ctx {
    const c = this._config!;
    const hot = new Set(alerts.filter((a) => a.roomBadge === "Too hot" && a.room).map((a) => a.room!));
    return {
      hass: this.hass!,
      config: c.atlas,
      alerts,
      badges: roomBadges(alerts),
      hot,
      floorId: c.floor,
      roomId: c.room,
      narrow: this._narrow,
      tick: this._tick,
      go: (p) => goView(p),
      href: (p) => navigate(p),
      openRoom: (r) => goView(`room-${typeof r === "string" ? r : r.id}`),
      moreInfo: (id) => moreInfo(this, id),
      call: this._call,
      confirm: (title, text, action, ok = "Confirm") => (this._confirm = { title, text, action, ok }),
      openAlert: (a) => {
        if (a.room) goView(`room-${a.room}`);
        else if (a.entity) moreInfo(this, a.entity);
        else if (a.href) navigate(a.href);
        else goView("alerts");
      },
      refresh: () => this.requestUpdate(),
      ui: UI_STATE,
    };
  }

  render() {
    if (!this._config || !this.hass) return nothing;
    const c = this._config.atlas;
    const ap = c.appearance ?? {};
    const variant: Variant = this._prefs.variant ?? ap.variant ?? "warm_glass";
    const accent = this._prefs.accent && /^#[0-9a-fA-F]{6}$/.test(this._prefs.accent) ? this._prefs.accent : accentOf(c);
    const mood = MOODS[ap.ambience ?? "graphite"] ?? MOODS.graphite;
    const a = rgb(accent);
    const style = `--atlas-accent:${accent};--atlas-accent-soft:rgba(${a},0.16);--atlas-accent-glow:rgba(${a},0.45);--atlas-tile:${mood.tile}`;

    if (!rooms(c).length) {
      return html`<div class="root v-quiet" style=${style}><div class="frame"><div class="main">
        <section class="glass card" style="max-width:640px;margin:10vh auto;gap:14px">
          <h2 style="font-size:24px">${icon("home", 28)}ATLAS Home</h2>
          <p class="t2">No rooms configured yet. Open the dashboard menu, choose <b>Edit dashboard</b>, then <b>Load demo house</b> or paste your own config in YAML mode, and save.</p>
        </section></div></div></div>`;
    }

    const alerts = evaluateAlerts(this.hass, c);
    const ctx = this._ctx(alerts);
    const view = this._config.view;
    const room = view === "room" ? roomById(c, this._config.room) : undefined;
    const photo = variant === "warm_glass" ? imageUrl(c, room?.image ? room : roomById(c, ap.background) ?? rooms(c)[0]) : undefined;

    let body;
    if (view === "home") body = renderHome(ctx);
    else if (view === "alerts") body = renderAlerts(ctx);
    else if (view === "rooms") body = renderRooms(ctx);
    else if (view === "energy") body = renderEnergy(ctx);
    else body = renderRoom(ctx);

    return html`<div class="root v-${variant}" style=${style}>
      ${this._background(variant, mood, photo)}
      <div class="frame">
        ${this._sidebar(ctx)}
        <div class="main">
          ${this._topbar(ctx)}
          ${body}
        </div>
      </div>
      ${this._bottomNav(ctx)}
      ${this._settings ? this._settingsPanel(variant, accent) : nothing}
      ${this._confirm ? this._confirmDialog() : nothing}
    </div>`;
  }

  private _background(variant: Variant, m: (typeof MOODS)[string], photo?: string) {
    if (variant === "quiet") return html`<div class="bg" style="background:var(--atlas-canvas)"></div>`;
    const blob = (l: number, t: number, w: number, h: number, c: string, b: number) =>
      html`<div class="blob" style="left:${l}%;top:${t}%;width:${w}px;height:${h}px;background:${c};filter:blur(${b}px)"></div>`;
    return html`<div class="bg" aria-hidden="true" style="background:linear-gradient(180deg,${m.base[0]} 0%,${m.base[1]} 60%,${m.base[2]} 100%)">
      ${blob(4, 2, 520, 380, m.g[0], 90)}${blob(62, -6, 640, 420, m.g[1], 100)}${blob(78, 40, 300, 300, m.g[2], 70)}${blob(30, 55, 700, 360, m.g[3], 80)}
      ${blob(12, 18, 60, 60, m.light, 14)}${blob(52, 10, 46, 46, m.light, 12)}${blob(88, 22, 70, 70, m.light, 16)}${blob(70, 78, 50, 50, m.light, 14)}
      ${photo ? html`<img class="photo" src=${photo} alt="" /><div class="tint" style="background:linear-gradient(180deg,rgba(${m.dark},0.35) 0%,rgba(${m.dark},0.6) 100%)"></div>` : nothing}
    </div>`;
  }

  private _sidebar(ctx: Ctx) {
    const v = this._config!.view;
    const e = ctx.config.entities ?? {};
    const energyNav = this._energyNav(ctx);
    const items: [string, string, boolean, () => void][] = [
      ["Home", "home", v === "home" || v === "alerts", () => ctx.go("home")],
      ["Rooms", "rooms", v === "rooms" || v === "room", () => ctx.go("rooms")],
      ["Energy", "energy", v === "energy", energyNav],
      ["Climate", "climate", false, () => (e.heat_pump ? ctx.moreInfo(e.heat_pump) : undefined)],
      ["Security", "security", false, () => (e.alarm ? ctx.moreInfo(e.alarm) : undefined)],
      ["Automations", "automations", false, () => ctx.href("/config/automation/dashboard")],
      ["System", "system", false, () => ctx.href("/config/system")],
    ];
    const user = this.hass!.user?.name ?? "";
    return html`<aside class="glass">
      <button class="logo" @click=${() => ctx.go("home")}>${icon("home", 34)}<span class="lt"><b>ATLAS</b><small>Smart Home</small></span></button>
      <nav class="nav" aria-label="Main">
        ${items.map(([label, ic, on, fn]) => html`<button class=${on ? "on" : ""} aria-current=${on ? "page" : "false"} title=${label} @click=${fn}>${icon(ic, 20)}<span class="lbl">${label}</span></button>`)}
      </nav>
      ${user ? html`<div class="user"><span class="avatar">${user.charAt(0).toUpperCase()}</span><span class="lbl">${user}</span></div>` : nothing}
    </aside>`;
  }

  private _topbar(ctx: Ctx) {
    const v = this._config!.view;
    const e = ctx.config.entities ?? {};
    const tabs: [string, string, boolean][] = [
      ["Home", "home", v === "home" || v === "alerts"],
      ...(ctx.config.layout?.top_tabs ?? [])
        .map((id) => roomById(ctx.config, id))
        .filter((r): r is RoomConfig => !!r)
        .map((r): [string, string, boolean] => [r.name, `room-${r.id}`, v === "room" && this._config!.room === r.id]),
      ["All rooms", "rooms", v === "rooms"],
    ];
    const w = stateObj(this.hass, e.weather);
    const out = num(this.hass, e.outdoor_temperature) ?? (isInvalid(w) ? undefined : Number(w!.attributes.temperature));
    const now = new Date();
    const lang = this.hass!.locale?.language ?? this.hass!.language ?? "en";
    const date = now.toLocaleDateString(lang, { weekday: "short", day: "numeric", month: "short" });
    const time = now.toLocaleTimeString(lang, { hour: "2-digit", minute: "2-digit", hour12: false });
    return html`<header class="glass top">
      <span class="mlogo">${icon("home", 24)}<b>ATLAS</b></span>
      <div class="tabs" role="tablist" aria-label="Views">
        ${tabs.map(([label, path, on]) => html`<button role="tab" aria-selected=${on ? "true" : "false"} class=${on ? "on" : ""} @click=${() => ctx.go(path)}>${label}</button>`)}
      </div>
      <div class="tools">
        ${e.weather || e.outdoor_temperature
          ? html`<button class="weather" @click=${() => e.weather && ctx.moreInfo(e.weather)}>
              ${weatherIcon(isInvalid(w) ? undefined : w!.state)}
              <span><span class="n" style="font-size:15px;font-weight:600">${out !== undefined && Number.isFinite(out) ? `${out.toFixed(1)} °C` : "–"}</span>
              <span class="t2 wtxt" style="font-size:11px">${w && !isInvalid(w) ? formatState(this.hass!, w) : "Weather unavailable"} · ${date}</span></span>
            </button>`
          : nothing}
        <span class="clock n">${time}</span>
        <button class="iconbtn" aria-label="Display settings" @click=${() => (this._settings = !this._settings)}>${icon("settings", 22)}</button>
      </div>
    </header>`;
  }

  /** ATLAS Energy view when meters are configured, else the built-in HA Energy dashboard. */
  private _energyNav(ctx: Ctx) {
    return () => (energyMeters(ctx.config).length ? ctx.go("energy") : ctx.href("/energy"));
  }

  private _bottomNav(ctx: Ctx) {
    const v = this._config!.view;
    const e = ctx.config.entities ?? {};
    const energyNav = this._energyNav(ctx);
    const items: [string, string, boolean, () => void][] = [
      ["Home", "home", v === "home", () => ctx.go("home")],
      ["Rooms", "rooms", v === "rooms" || v === "room", () => ctx.go("rooms")],
      ["Energy", "energy", v === "energy", energyNav],
      ["Climate", "climate", false, () => (e.heat_pump ? ctx.moreInfo(e.heat_pump) : undefined)],
      ["Alerts", "alert", v === "alerts", () => ctx.go("alerts")],
    ];
    return html`<nav class="glass bnav" aria-label="Main">
      ${items.map(([label, ic, on, fn]) => html`<button class=${on ? "on" : ""} @click=${fn}>${icon(ic, 22)}${label}</button>`)}
    </nav>`;
  }

  private _settingsPanel(variant: Variant, accent: string) {
    const set = (p: DevicePrefs) => {
      this._prefs = { ...this._prefs, ...p };
      savePrefs(this._prefs);
    };
    const V: [Variant, string][] = [["warm_glass", "Warm glass"], ["glass", "Glass"], ["quiet", "Quiet"]];
    return html`<div class="settings" role="dialog" aria-label="Display settings">
      <div class="row"><b>Display on this device</b><button class="iconbtn" aria-label="Close" @click=${() => (this._settings = false)}>✕</button></div>
      <span class="t2" style="font-size:12px">Style</span>
      <div class="seg">${V.map(([k, l]) => html`<button class=${variant === k ? "on" : ""} @click=${() => set({ variant: k })}>${l}</button>`)}</div>
      <span class="t2" style="font-size:12px">Accent</span>
      <div class="seg">${ACCENT_PRESETS.map((c) => html`<button class="sw ${accent === c ? "on" : ""}" style="background:${c}" aria-label="Accent ${c}" @click=${() => set({ accent: c })}></button>`)}</div>
      <button class="ctl" @click=${() => { this._prefs = {}; savePrefs({}); }}>Use dashboard defaults</button>
      <span class="t2" style="font-size:11px">Stored in this browser only. Defaults and all entities are set in Edit dashboard.</span>
    </div>`;
  }

  private _confirmDialog() {
    const d = this._confirm!;
    const close = () => (this._confirm = undefined);
    return html`<div class="scrim" @click=${close}>
      <div class="dialog" role="alertdialog" aria-modal="true" aria-label=${d.title} @click=${(e: Event) => e.stopPropagation()}>
        <h2>${d.title}</h2>
        <p class="t2">${d.text}</p>
        <div class="acts">
          <button class="ctl" @click=${close}>Cancel</button>
          <button class="ctl ok" @click=${() => { close(); d.action(); }}>${d.ok}</button>
        </div>
      </div>
    </div>`;
  }
}
