// Converts assets/icons/<name>-white.svg into src/ui/icons.generated.ts
// and lists public/rooms images in src/config/images.generated.ts.
// The stroke colour is replaced with currentColor so one icon serves every tint.
import { readdirSync, readFileSync, writeFileSync, mkdirSync } from "node:fs";

const dir = "assets/icons";
const out = {};
for (const file of readdirSync(dir).sort()) {
  if (!file.endsWith("-white.svg")) continue;
  const name = file.replace(/-white\.svg$/, "");
  const svg = readFileSync(`${dir}/${file}`, "utf8");
  const inner = svg.replace(/^[\s\S]*?<svg[^>]*>/, "").replace(/<\/svg>\s*$/, "");
  out[name] = inner.replace(/#F1F5FF/gi, "currentColor").trim();
}
mkdirSync("src/ui", { recursive: true });
writeFileSync(
  "src/ui/icons.generated.ts",
  "// Generated by scripts/build-icons.mjs - do not edit.\n" +
    "export const ICONS: Record<string, string> = " + JSON.stringify(out, null, 2) + ";\n"
);
console.log(`icons: ${Object.keys(out).length}`);

// Room images shipped in public/rooms (copied to dist/rooms): used by the editor's
// image picker and by the automatic image for rooms whose id matches a file name.
const walk = (d, pre = "") =>
  readdirSync(d, { withFileTypes: true }).flatMap((e) =>
    e.isDirectory() ? walk(`${d}/${e.name}`, `${pre}${e.name}/`) : /\.(jpe?g|png|webp)$/i.test(e.name) ? [`${pre}${e.name}`] : []
  );
const images = walk("public/rooms").sort();
writeFileSync(
  "src/config/images.generated.ts",
  "// Generated by scripts/build-icons.mjs from public/rooms - do not edit.\n" +
    "export const SHIPPED_IMAGES: string[] = " + JSON.stringify(images, null, 2) + ";\n"
);
console.log(`room images: ${images.length}`);
